# Generates vk64pe.c: 64-bit-correct PE vulkan-1.dll shim
import sys

exports = []
import os
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'exports.txt')) as f:
    for line in f:
        parts = line.strip().split()
        if len(parts) == 3:
            exports.append((parts[0], int(parts[1]) if parts[1] != 'None' else None, int(parts[2])))

loaders = {'vkGetDeviceProcAddr', 'vkGetInstanceProcAddr', 'vk_icdGetInstanceProcAddr',
           'vk_icdGetPhysicalDeviceProcAddr', 'vk_icdNegotiateLoaderICDInterfaceVersion'}

normal = [(n,f,a) for n,f,a in exports if n not in loaders and f != 1]
unimpl = [(n,f,a) for n,f,a in exports if n not in loaders and f == 1]

print(f"normal={len(normal)} unimpl={len(unimpl)} loaders={len(loaders)}", file=sys.stderr)

out = []
out.append('''/* vk64pe.c - 64-bit-correct PE vulkan-1.dll shim for Boxedwine64.
 * Generated by gen_vk64pe.py. DO NOT EDIT MANUALLY.
 *
 * Each export traps to the host vk64bridge via the private syscall:
 *   RAX = 0x564b0000 (VK64_SYSCALL_NR)
 *   RDI = function id (VK64_fn_*)
 *   RSI = guest VA of VK64Args { uint64_t a[16] }
 *
 * CRITICAL: All arguments are passed as full 64-bit values in the args array.
 * The previous DLL truncated pointers to 32-bit (mov %r32,%eax), corrupting
 * any guest pointer above 4GB (e.g. 0x14000d030 -> 0x4000d030).
 */
#include <stdint.h>
#include <string.h>

#define VK64_SYSCALL_NR ((uint64_t)0x564b0000ULL)

static inline uint64_t vk64_trap(uint64_t fnId, uint64_t *args) {
    uint64_t ret;
    __asm__ volatile (
        "syscall"
        : "=a"(ret)
        : "a"(VK64_SYSCALL_NR), "D"(fnId), "S"(args)
        : "rcx", "r11", "memory"
    );
    return ret;
}
''')

# Normal trap stubs
for name, fnid, argc in normal:
    params = ', '.join(f'uint64_t a{i}' for i in range(argc)) if argc else 'void'
    inits = ', '.join(f'a{i}' for i in range(argc))
    if name in {'vkCmdSetViewportWithCount', 'vkCmdSetViewportWithCountEXT',
                'vkCmdSetScissorWithCount', 'vkCmdSetScissorWithCountEXT'}:
        # The host uses the canonical (cmd, first, count, pointer) trap ABI.
        # WithCount omits first, which is implicitly zero.
        if argc != 3:
            raise ValueError(f'{name} must have three public arguments')
        inits = 'a0, 0, a1, a2'
    out.append(f'__declspec(dllexport) uint64_t {name}({params}) {{')
    out.append(f'    uint64_t args[16] = {{{inits}}};')
    out.append(f'    return vk64_trap({fnid}ULL, args);')
    out.append('}')
    out.append('')

# Unimplemented stubs (fnId=1, return VK_ERROR_FEATURE_NOT_PRESENT = -8)
for name, fnid, argc in unimpl:
    out.append(f'__declspec(dllexport) uint64_t {name}(void) {{')
    out.append(f'    uint64_t args[16] = {{(uint64_t)"{name}"}};')
    out.append(f'    vk64_trap(1ULL, args);')
    out.append(f'    return (uint64_t)(int64_t)-8;')
    out.append('}')
    out.append('')

# Proc table for loader functions (all exports)
out.append('typedef struct { const char *name; void *func; } ProcEntry;')
out.append('// Forward declarations for loader functions (defined below g_procs)')
out.append('__declspec(dllexport) void *vkGetDeviceProcAddr(uint64_t device, const char *name);')
out.append('__declspec(dllexport) void *vkGetInstanceProcAddr(uint64_t instance, const char *name);')
out.append('__declspec(dllexport) void *vk_icdGetInstanceProcAddr(uint64_t instance, const char *name);')
out.append('__declspec(dllexport) void *vk_icdGetPhysicalDeviceProcAddr(uint64_t instance, const char *name);')
out.append('__declspec(dllexport) uint32_t vk_icdNegotiateLoaderICDInterfaceVersion(uint32_t *pVersion);')
out.append('static ProcEntry g_procs[] = {')
for name, fnid, argc in exports:
    if True:  # Include loaders so they are resolvable via vkGetInstanceProcAddr
        out.append(f'    {{"{name}", (void*){name}}},')
out.append('};')
out.append('static const int g_nprocs = sizeof(g_procs) / sizeof(g_procs[0]);')
out.append('')
out.append('''/* Benign stub for unknown proc names. Traps with fnId=1 (unimplemented)
 * so the host logs the request, then returns VK_ERROR_FEATURE_NOT_PRESENT.
 * For vkd3d-queried functions with output params, writes plausible defaults
 * to prevent infinite retry loops. */
static __thread uint64_t vk64_benign_name = 0;
__declspec(dllexport) uint64_t vk64_benign(uint64_t a0, uint64_t a1, uint64_t a2) {
    uint64_t args[16] = {vk64_benign_name};
    const char *name = (const char*)vk64_benign_name;
    vk64_trap(1ULL, args);
    if (name && a2) {
        if (strcmp(name, "vkGetPhysicalDeviceSurfaceCapabilities2KHR") == 0) {
            uint32_t *out = (uint32_t*)a2;
            out[0] = 1000119001;
            out[1] = 0;
            for (int i = 2; i < 32; i++) out[i] = 0;
            out[2] = 2;
            out[3] = 8;
            return 0;
        }
    }
    (void)a0; (void)a1;
    return (uint64_t)(int64_t)-8;
}

/* Denylist: extension functions that cause vkd3d to spin if stubbed.
 * Return NULL so vkd3d disables the extension cleanly. */
static const char *g_denylist[] = {
    "vkGetDescriptorSetLayoutSizeEXT",
    "vkGetDescriptorSetLayoutBindingOffsetEXT",
    "vkGetDescriptorEXT",
    "vkCmdBindDescriptorBuffersEXT",
    "vkCmdSetDescriptorBufferOffsetsEXT",
    "vkCmdBindDescriptorBufferEmbeddedSamplersEXT",
    "vkGetBufferOpaqueCaptureDescriptorDataEXT",
    "vkGetImageOpaqueCaptureDescriptorDataEXT",
    "vkGetImageViewOpaqueCaptureDescriptorDataEXT",
    "vkGetSamplerOpaqueCaptureDescriptorDataEXT",
    "vkGetAccelerationStructureOpaqueCaptureDescriptorDataEXT",
    "vkGetPhysicalDeviceCooperativeMatrixPropertiesKHR",
    "vkGetPhysicalDeviceCooperativeMatrixPropertiesNV",
    "vkGetPhysicalDeviceDescriptorSizeEXT",
};
static const int g_ndenylist = 14;
static int vk64_is_denylisted(const char *name) {
    int i;
    for (i = 0; i < g_ndenylist; i++)
        if (strcmp(name, g_denylist[i]) == 0) return 1;
    return 0;
}

static void *vk64_resolve(const char *name) {
    if (!name) return (void*)vk64_benign;
    if (vk64_is_denylisted(name)) return NULL;
    for (int i = 0; i < g_nprocs; i++) {
        if (strcmp(name, g_procs[i].name) == 0)
            return g_procs[i].func;
    }
    /* Never return NULL: vkd3d expects a valid pointer even for unknown
     * names (e.g. vkEnumerateDeviceLayerProperties). Return benign stub. */
    vk64_benign_name = (uint64_t)name;
    return (void*)vk64_benign;
}

__declspec(dllexport) void *vkGetInstanceProcAddr(uint64_t instance, const char *name) {
    (void)instance;
    return vk64_resolve(name);
}

__declspec(dllexport) void *vkGetDeviceProcAddr(uint64_t device, const char *name) {
    void *p = vk64_resolve(name);
    if (p) return p;
    return vkGetInstanceProcAddr(device, name);
}

__declspec(dllexport) void *vk_icdGetInstanceProcAddr(uint64_t instance, const char *name) {
    return vkGetInstanceProcAddr(instance, name);
}

__declspec(dllexport) void *vk_icdGetPhysicalDeviceProcAddr(uint64_t instance, const char *name) {
    return vkGetInstanceProcAddr(instance, name);
}

__declspec(dllexport) uint32_t vk_icdNegotiateLoaderICDInterfaceVersion(uint32_t *pVersion) {
    if (pVersion) *pVersion = 5;
    return 0;
}
''')

with open('/tmp/vk64pe.c', 'w') as f:
    f.write('\n'.join(out))
print("wrote /tmp/vk64pe.c", file=sys.stderr)
