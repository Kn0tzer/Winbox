#!/usr/bin/env python3
"""generate vk64_guest.h from the in-tree Khronos vulkan_core.h.

Why this exists
---------------
source/vulkan/vk64bridge.cpp reads Vulkan structs OUT OF x86-64 GUEST MEMORY, but
it compiles into the wasm32 Emscripten build, where a host pointer is FOUR bytes
and the guest's is EIGHT. So the in-tree header's `const void* pNext` /
`const char* const* ppEnabledExtensionNames` / `const VkCommandBuffer*
pCommandBuffers` members are the wrong width: copying a host-typed struct out of
guest memory would read the fields after the first pointer from the wrong
offsets. The existing 32-bit bridge solves the same problem the hard way — a
604 KB field-by-field marshaller (source/vulkan/vk_host_marshal.h, generated by
tools/vulkan/gen).

This generator produces the cheap equivalent for the 64-bit boundary: for each
struct the bridge touches, the SAME declaration with every pointer/handle member
replaced by uint64_t. That is exactly the x86-64 guest layout, so the whole file
can be `memcpyFromGuest`'d one struct at a time — which is what the bridge does
and what gl64bridge.cpp does for GL.

Usage:  python3 tools/vulkan/gen/gen_vk64_guest.py source/vulkan/vk/vulkan_core.h \
            > source/vulkan/vk64_guest.h

Verifying the output (what "generated == guest ABI" means, mechanically): compile
a probe that prints sizeof/offsetof for every struct the bridge touches ONCE
against the real vulkan_core.h with VK_USE_64_BIT_PTR_DEFINES=1 (an LP64 host, so
the pointers are already 8 bytes) and ONCE against the generated header, then
diff. The static_asserts at the bottom of the generated header are exactly that
comparison baked into the build.
"""
