#!/usr/bin/env python3
"""Generate docs/known-gaps/runtime-artifact-manifest.md from the shipped
runtime artifacts (docs/known-gaps/runtime.md evidence base).

The runtime register's NOT-A-GAP / IMPLEMENTED rows make presence and
absence claims about DLLs in the shipped zips. Before this manifest those
claims rested on the lane's word; now the exact zip members they depend on
are listed in a checked-in file generated from the artifacts themselves,
and check_runtime_completeness.py fails if the manifest drifts from the
zips on disk. Regenerate after any zip re-staging:

    python3 tools/rootfs64/gen_runtime_manifest.py

Deterministic output (no timestamps): zip provenance is pinned by
sha256 + byte size + member count.
"""
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs/known-gaps/runtime-artifact-manifest.md'


def support_zip_path():
    deps = json.loads((ROOT / 'dist/runtime/dependencies.json').read_text())
    return ROOT / 'dist/runtime' / deps['archive']


ZIPS = [
    ('w64', ROOT / 'web/runtime/wine64.zip'),
    ('w32', ROOT / 'web/runtime/wine32.zip'),
    ('p64', ROOT / 'web/runtime/prefix64.zip'),
    ('p32', ROOT / 'web/runtime/prefix32.zip'),
    ('g64', ROOT / 'web/runtime/glibc-rootfs64.zip'),
    ('g32', ROOT / 'web/runtime/glibc-rootfs32.zip'),
    ('support', support_zip_path()),
]

VC_FAMILY = re.compile(r'(msvcp|msvcr|vcruntime|ucrtbase|concrt)', re.I)
DX_FAMILY = re.compile(r'(d3dx9_|d3dx10_|d3dx11_|d3dcompiler_)', re.I)
DX_CORE = {'d3d8.dll', 'd3d9.dll', 'd3d10.dll', 'd3d10core.dll', 'd3d11.dll',
           'd3d12.dll', 'd3d12core.dll', 'dxgi.dll', 'dinput.dll',
           'dinput8.dll', 'dplay.dll', 'dplayx.dll', 'dpnet.dll',
           'dplaysvr.exe', 'ddraw.dll', 'dsound.dll', 'xinput1_1.dll',
           'xinput1_2.dll', 'xinput1_3.dll', 'xinput1_4.dll',
           'xinput9_1_0.dll', 'xinputuap.dll', 'winexinput.sys'}
XACT_FAMILY = re.compile(r'(xaudio2_|xactengine|x3daudio)', re.I)
MEDIA = {'mfplat.dll', 'mfreadwrite.dll', 'mf.dll', 'quartz.dll',
         'wmvcore.dll', 'evr.dll', 'amstream.dll', 'msmpeg2vdec.dll',
         'winegstreamer.so', 'winegstreamer.dll.so'}
MISC = {'winealsa.drv', 'winmm.dll', 'vulkan-1.dll', 'opengl32.dll',
        'opengl32.so', 'winhttp.dll', 'wininet.dll', 'ws2_32.dll',
        'ws2_32.so', 'dnsapi.dll', 'dnsapi.so', 'dnsapi.dll.so',
        'crypt32.dll', 'crypt32.so', 'bcrypt.dll', 'bcrypt.so',
        'secur32.dll', 'secur32.so', 'mscoree.dll', 'tahoma.ttf',
        'tahomabd.ttf', 'openal32.dll'}
ABSENT_EVERYWHERE = ['steam_api.dll', 'steam_api64.dll', 'steamclient.dll',
                     'mfc140.dll', 'mfc140u.dll', 'faudio.dll']


def basename(name):
    return name.rsplit('/', 1)[-1]


def build_manifest():
    data = {}
    for label, path in ZIPS:
        with zipfile.ZipFile(path) as z:
            infos = {i.filename: i for i in z.infolist()}
        data[label] = (path, infos)
    lines = []
    lines.append('# Runtime artifact manifest (generated)')
    lines.append('')
    lines.append('Generated by `tools/rootfs64/gen_runtime_manifest.py` from the')
    lines.append('shipped artifacts on disk. Do not edit by hand; regenerate after')
    lines.append('re-staging any zip. `check_runtime_completeness.py` (check')
    lines.append('`manifest matches shipped zips`) fails when this file drifts')
    lines.append('from the artifacts, so the register rows citing it stay honest.')
    lines.append('')
    lines.append('## Zip provenance')
    lines.append('')
    lines.append('| Label | Path | Bytes | sha256 | Members |')
    lines.append('| --- | --- | --- | --- | --- |')
    for label, path in ZIPS:
        raw = path.read_bytes()
        rel = path.relative_to(ROOT)
        lines.append(f'| {label} | `{rel}` | {len(raw)} | `{hashlib.sha256(raw).hexdigest()}` | {len(data[label][1])} |')
    lines.append('')
    lines.append('Labels match the register legend in `runtime.md`')
    lines.append('(`w64` = wine64.zip, `w32` = wine32.zip, `p64`/`p32` = prefix zips,')
    lines.append('`support` = the support pack named by `dist/runtime/dependencies.json`).')
    lines.append('')

    def census(title, labels, predicate, note=None):
        lines.append(f'## {title}')
        lines.append('')
        if note:
            lines.append(note)
            lines.append('')
        for label in labels:
            infos = data[label][1]
            hits = sorted(n for n in infos if predicate(basename(n), n))
            lines.append(f'### {label} ({len(hits)})')
            lines.append('')
            for n in hits:
                lines.append(f'- `{n}` ({infos[n].file_size} bytes)')
            if not hits:
                lines.append('- (none)')
            lines.append('')

    def gst_placement(data):
        # The gstreamer plugin set + DT_NEEDED closure staged by
        # prepare-gstreamer.py rides the lazy support pack since the
        # 2026-10-25 split; the boot zips must carry none of it. Expected
        # guest paths come from the staged source trees; presence is read
        # from the artifacts themselves, so any drift fails the manifest
        # check in check_runtime_completeness.py.
        lines.append('## GStreamer closure placement (lazy support pack)')
        lines.append('')
        support = data['support'][1]
        for stage_dir, boot in (('gstreamer64', 'w64'), ('gstreamer32', 'w32')):
            root = ROOT / 'tools/rootfs64' / stage_dir
            paths = sorted(p.relative_to(root).as_posix()
                           for p in root.rglob('*') if p.is_file())
            in_boot = [n for n in paths if n in data[boot][1]]
            in_support = [n for n in paths if n in support]
            missing = [n for n in paths if n not in support]
            total = sum(support[n].file_size for n in in_support)
            lines.append(f'- {stage_dir} closure: {len(paths)} staged members; '
                         f'in {boot}: {len(in_boot)} (must be 0); '
                         f'in support: {len(in_support)} ({total} bytes)')
            for n in in_boot:
                lines.append(f'  - UNEXPECTED in {boot}: `{n}`')
            for n in missing:
                lines.append(f'  - MISSING from support: `{n}`')
        lines.append('')

    def alsa_bridge(data):
        # The ALSA-to-OSS bridge (M5): winealsa.drv resolves "default" via
        # libasound, and the rootfs has no real ALSA cards, so the bridge
        # routes audio to the emulated OSS /dev/dsp. Its members are
        # staged from the checked-in trees tools/rootfs64/alsa (x86_64;
        # baked into wine64.zip by build-wine64-zip.sh) and
        # tools/rootfs64/alsa32 (i386; added to wine32.zip +
        # glibc-rootfs32.zip by stage-alsa32.sh). glibc-rootfs64.zip's
        # etc/asound.conf is printf-generated by build-wine64-zip.sh;
        # check_runtime_completeness.py asserts it stays byte-identical
        # to the canonical alsa32/etc/asound.conf. Until 2026-10-25 no
        # census named these members, and the 32-bit bridge was in fact
        # absent from the shipped zips (restored the same day); expected
        # sets here come from the staged trees and presence/bytes from
        # the artifacts, so drift in either direction is listed by name.
        lines.append('## ALSA-to-OSS bridge census (staging-tree anchored)')
        lines.append('')
        lines.append('Provenance: x86_64 members from Debian bookworm'
                     ' `libasound2` + `libasound2-plugins` (refresh record:'
                     ' `tools/rootfs64/alsa/README`, which records packages,'
                     ' not versions). i386 plugin members from Debian'
                     ' `libasound2-plugins` 1.2.7.1-1 and the i386 config'
                     ' tree from the same extraction (refresh record:'
                     ' `tools/rootfs64/alsa32/README`). `etc/asound.conf`'
                     ' carries the canonical plug-to-OSS default'
                     ' (`tools/rootfs64/alsa32/etc/asound.conf`).')
        lines.append('')
        t64 = ROOT / 'tools/rootfs64/alsa'
        t32 = ROOT / 'tools/rootfs64/alsa32'

        def tree_files(root):
            return {q.relative_to(root).as_posix() for q in root.rglob('*')
                    if q.is_file() and q.name != 'README'}

        files32 = tree_files(t32)
        plan = [
            ('w64', tree_files(t64),
             lambda n: 'alsa-lib/' in n or n.startswith('usr/share/alsa/')),
            ('w32', {n for n in files32 if '/alsa-lib/' in n},
             lambda n: 'alsa-lib/' in n or n.startswith('usr/share/alsa/')),
            ('g32', {n for n in files32 if n == 'etc/asound.conf'
                     or n.startswith('usr/share/alsa/')},
             lambda n: n == 'etc/asound.conf' or 'alsa-lib/' in n
             or n.startswith('usr/share/alsa/')),
            ('g64', {'etc/asound.conf'},
             lambda n: n == 'etc/asound.conf'),
        ]
        for label, expected, in_class in plan:
            path, infos = data[label]
            with zipfile.ZipFile(path) as z:
                contents = {n: z.read(n) for n in infos
                            if in_class(n) and not n.endswith('/')}
            actual = set(contents)
            lines.append(f'### {label} ({len(expected & actual)}/{len(expected)} expected present)')
            lines.append('')
            for n in sorted(expected | actual):
                if n in expected and n in actual:
                    digest = hashlib.sha256(contents[n]).hexdigest()
                    lines.append(f'- `{n}` ({len(contents[n])} bytes, sha256 `{digest}`)')
                elif n in expected:
                    lines.append(f'  - MISSING from {label}: `{n}`')
                else:
                    lines.append(f'  - UNEXPECTED in {label}: `{n}`')
            lines.append('')

    def absent(title, names, labels):
        lines.append(f'## {title}')
        lines.append('')
        for name in names:
            for label in labels:
                infos = data[label][1]
                hits = [n for n in infos if basename(n).lower() == name]
                state = 'PRESENT: ' + ', '.join(sorted(hits)) if hits else 'ABSENT'
                lines.append(f'- `{name}` in {label}: {state}')
        lines.append('')

    census('VC++ runtime census (msvcp/msvcr/vcruntime/ucrtbase/concrt basenames)',
           ('w64', 'w32'), lambda b, n: bool(VC_FAMILY.match(b)))
    census('DirectX numbered families (d3dx9_/d3dx10_/d3dx11_/d3dcompiler_)',
           ('w64', 'w32'), lambda b, n: bool(DX_FAMILY.match(b)))
    census('DirectX core + input set', ('w64', 'w32'),
           lambda b, n: b.lower() in DX_CORE)
    census('XAudio2 / XACT / X3DAudio census', ('w64', 'w32'),
           lambda b, n: bool(XACT_FAMILY.match(b)))
    census('Media Foundation / gstreamer set', ('w64', 'w32'),
           lambda b, n: b.lower() in MEDIA)
    census('GStreamer plugin members (gstreamer-1.0/)', ('w64', 'w32', 'support'),
           lambda b, n: 'gstreamer-1.0/' in n)
    gst_placement(data)
    census('Audio / graphics / networking / TLS / fonts set', ('w64', 'w32', 'support'),
           lambda b, n: b.lower() in MISC)
    alsa_bridge(data)
    census('Wineserver members', ('w64', 'w32'),
           lambda b, n: 'wineserver' in n,
           note=('Member *contents* for the symlink-form entries are pinned by\n'
                 '`check_runtime_completeness.py` (`wineserver dispatch is ELF`,\n'
                 'which asserts `usr/lib/wine/wineserver` and `usr/bin/wineserver`\n'
                 'in w64 both carry the target text `/usr/lib/wine/wineserver64`\n'
                 'and that `wineserver64` itself is an ELF binary).'))
    census('Support-pack .NET / Gecko / OpenAL members', ('support',),
           lambda b, n: ('libmono-2.0' in n or 'wine-mono' in n or 'gecko' in n
                         or b.lower() == 'openal32.dll' or 'wqy' in n.lower()
                         or 'microhei' in n.lower()))
    census('Prefix DXVK override DLLs (32-bit prefix root)', ('p32',),
           lambda b, n: n in ('home/username/d3d9.dll', 'home/username/d3d11.dll',
                              'home/username/dxgi.dll'))
    census('32-bit rootfs DejaVu faces', ('g32',),
           lambda b, n: 'dejavu' in n.lower() and n.endswith('.ttf'))
    absent('Claimed absences (register rows cite these)',
           ['vcruntime140_1.dll (i386-only absence is upstream-correct; see per-zip lines below)'],
           ())
    lines.append('Per-name absence/presence for the asymmetric and')
    lines.append('non-existence claims:')
    lines.append('')
    for name in ('vcruntime140_1.dll', 'msvcp140_codecvt_ids.dll',
                 'd3dcompiler_24.dll', 'd3dcompiler_32.dll',
                 'd3dcompiler_44.dll', 'd3dcompiler_45.dll',
                 'd3dx10.dll', 'd3dx11.dll'):
        for label in ('w64', 'w32'):
            infos = data[label][1]
            hits = [n for n in infos if basename(n).lower() == name]
            state = 'PRESENT: ' + ', '.join(sorted(hits)) if hits else 'ABSENT'
            lines.append(f'- `{name}` in {label}: {state}')
    lines.append('')
    absent('Absent in both wine zips (proprietary / per-game / unimplemented-upstream)',
           ABSENT_EVERYWHERE, ('w64', 'w32'))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = build_manifest()
    if '--check' in sys.argv:
        current = OUT.read_text() if OUT.exists() else ''
        if current != text:
            print('manifest drift: regenerate with gen_runtime_manifest.py')
            sys.exit(1)
        print('manifest matches shipped zips')
    else:
        OUT.write_text(text)
        print(f'wrote {OUT} ({len(text)} bytes)')
