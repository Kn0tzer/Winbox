const toWgsl = (source) => String(naga.translate({ from: 'spirv', to: 'wgsl', source }));

test('R10: integer Vertex output gets Flat and naga accepts the module', () => {
  assert.throws(() => toWgsl(VS), /invalid/i, 'raw module must still be rejected (guards the premise)');
  const r = applySpirvFix(VS);
  assert.ok(r.applied.includes('flat-integer-varyings'), r.log.join('\n'));
  const flat = parseSpirv(r.bytes).insns.filter(i => i.op === 71 && i.words[1] === 14);
  assert.equal(flat.length, 1);
  assert.doesNotThrow(() => toWgsl(r.bytes));
});

test('R10: already-flat or float varyings are left alone', () => {
  const r = applySpirvFix(VS);
  assert.ok(!applySpirvFix(r.bytes).applied.includes('flat-integer-varyings'), 'idempotent');
});

test('R11: fragment BuiltIn Layer load becomes constant 0 and naga accepts the module', () => {
  assert.throws(() => toWgsl(FS), /UnsupportedBuiltIn/);
  const r = applySpirvFix(FS);
  assert.ok(r.applied.includes('fragment-layer-to-zero'), r.log.join('\n'));
  const out = parseSpirv(r.bytes);
  assert.ok(!out.insns.some(i => i.op === 71 && i.words[1] === 11 && i.words[2] === 9), 'Layer decoration gone');
  assert.doesNotThrow(() => toWgsl(r.bytes));
});
